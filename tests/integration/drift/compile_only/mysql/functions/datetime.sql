-- mysql · datetime functions

-- date_trunc(unit, x)
--   date_trunc('month', DATE '2026-08-15') = '2026-08-01'
CAST(DATE_FORMAT(CAST('2026-08-15' AS DATE), '%Y-%m-01') AS DATE);
--   date_trunc('quarter', DATE '2026-08-15') = '2026-07-01'
DATE_ADD(MAKEDATE(YEAR(CAST('2026-08-15' AS DATE)), 1), INTERVAL QUARTER(CAST('2026-08-15' AS DATE)) - 1 QUARTER);
--   date_trunc('week', DATE '2026-08-15') = '2026-08-10'
DATE(DATE_SUB(CAST('2026-08-15' AS DATE), INTERVAL WEEKDAY(CAST('2026-08-15' AS DATE)) DAY));
--   date_trunc('year', DATE '2026-08-15') = '2026-01-01'
CAST(DATE_FORMAT(CAST('2026-08-15' AS DATE), '%Y-01-01') AS DATE);

-- date_add(unit, n, x)
--   date_add('day', 5, DATE '2026-08-01') = '2026-08-06'
DATE_ADD(CAST('2026-08-01' AS DATE), INTERVAL 5 DAY);
--   date_add('day', -5, DATE '2026-08-01') = '2026-07-27'
DATE_ADD(CAST('2026-08-01' AS DATE), INTERVAL -5 DAY);
--   date_add('month', 1, DATE '2026-01-31') = '2026-02-28'
DATE_ADD(CAST('2026-01-31' AS DATE), INTERVAL 1 MONTH);
--   date_add('year', 1, DATE '2026-08-01') = '2027-08-01'
DATE_ADD(CAST('2026-08-01' AS DATE), INTERVAL 1 YEAR);

-- date_diff(unit, start, end)
--   date_diff('day', DATE '2026-08-01', DATE '2026-08-15') = 14
TIMESTAMPDIFF(DAY, CAST(DATE_FORMAT(CAST('2026-08-01' AS DATE), '%Y-%m-%d') AS DATE), CAST(DATE_FORMAT(CAST('2026-08-15' AS DATE), '%Y-%m-%d') AS DATE));
--   date_diff('week', DATE '2026-08-09', DATE '2026-08-15') = 1
(TIMESTAMPDIFF(DAY, CAST(DATE_FORMAT(DATE(DATE_SUB(CAST('2026-08-09' AS DATE), INTERVAL WEEKDAY(CAST('2026-08-09' AS DATE)) DAY)), '%Y-%m-%d') AS DATE), CAST(DATE_FORMAT(DATE(DATE_SUB(CAST('2026-08-15' AS DATE), INTERVAL WEEKDAY(CAST('2026-08-15' AS DATE)) DAY)), '%Y-%m-%d') AS DATE)) DIV 7);
--   date_diff('day', DATE '2026-08-15', DATE '2026-08-01') = -14
TIMESTAMPDIFF(DAY, CAST(DATE_FORMAT(CAST('2026-08-15' AS DATE), '%Y-%m-%d') AS DATE), CAST(DATE_FORMAT(CAST('2026-08-01' AS DATE), '%Y-%m-%d') AS DATE));
--   date_diff('month', DATE '2026-01-31', DATE '2026-03-01') = 2
TIMESTAMPDIFF(MONTH, CAST(DATE_FORMAT(CAST('2026-01-31' AS DATE), '%Y-%m-01') AS DATE), CAST(DATE_FORMAT(CAST('2026-03-01' AS DATE), '%Y-%m-01') AS DATE));
--   date_diff('year', DATE '2026-12-31', DATE '2027-01-01') = 1
TIMESTAMPDIFF(YEAR, CAST(DATE_FORMAT(CAST('2026-12-31' AS DATE), '%Y-01-01') AS DATE), CAST(DATE_FORMAT(CAST('2027-01-01' AS DATE), '%Y-01-01') AS DATE));

-- extract(unit, x)
--   extract('year', DATE '2026-08-15') = 2026
EXTRACT(YEAR FROM CAST('2026-08-15' AS DATE));
--   extract('month', DATE '2026-08-15') = 8
EXTRACT(MONTH FROM CAST('2026-08-15' AS DATE));
--   extract('quarter', DATE '2026-08-15') = 3
EXTRACT(QUARTER FROM CAST('2026-08-15' AS DATE));
--   extract('week', DATE '2026-08-15') = 33
WEEK(CAST('2026-08-15' AS DATE), 3);
--   extract('day', DATE '2026-08-15') = 15
EXTRACT(DAY FROM CAST('2026-08-15' AS DATE));

-- last_day(x)
--   last_day(DATE '2026-08-15') = '2026-08-31'
LAST_DAY(CAST('2026-08-15' AS DATE));
--   last_day(DATE '2026-02-01') = '2026-02-28'
LAST_DAY(CAST('2026-02-01' AS DATE));

-- current_date()
--   date_diff('day', current_date(), current_date()) = 0
TIMESTAMPDIFF(DAY, CAST(DATE_FORMAT(CURRENT_DATE(), '%Y-%m-%d') AS DATE), CAST(DATE_FORMAT(CURRENT_DATE(), '%Y-%m-%d') AS DATE));
